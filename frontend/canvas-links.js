function titleKey(title) {
  return String(title || "")
    .replace(/\s*\(\d+\)\s*$/, "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
}

function catalog(courseId, rows) {
  return Object.freeze(rows.map(([itemId, title]) => Object.freeze({
    title,
    kind: /\bKC\b/i.test(title) ? "kc" : "lab",
    url: `https://awsrestart.instructure.com/courses/${courseId}/modules/items/${itemId}`,
  })));
}

export const canvasCatalogs = Object.freeze({
  "4436": catalog("4436", rows4436),
  "4413": catalog("4413", rows4413),
});

// Não associar só pelo número: nomes iguais em turmas diferentes não provam
// que o item de módulo pertence ao curso do aluno.
export function canvasActivityEntry(courseId, activity) {
  if (!Object.hasOwn(canvasCatalogs, courseId)) return null;
  const matches = canvasCatalogs[courseId].filter((entry) =>
    entry.kind === activity.kind && titleKey(entry.title) === titleKey(activity.name),
  );
  return matches.length === 1 ? matches[0] : null;
}

export function canvasActivityLink(courseId, activity) {
  if (!["pending", "completed"].includes(activity.state)) return null;
  const entry = canvasActivityEntry(courseId, activity);
  if (!entry) return null;
  return {
    url: entry.url,
    label: activity.state === "completed"
      ? "Ver atividade no Canvas"
      : `Abrir ${activity.kind === "kc" ? "KC" : "LAB"} no Canvas`,
  };
}
